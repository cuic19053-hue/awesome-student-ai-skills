def build_one(cfg):
    # 表题登记表按文档取题，先告知当前文档键
    docx_kit.CURRENT_DOC = cfg["file"].replace("demo_", "").replace(".docx", "")
    doc = new_doc()
    doc.core_properties.title = cfg["title"]
    doc.core_properties.subject = cfg["kind"].replace(" ", "")
    cover(doc, cfg["org"], cfg["kind"], cfg["title"],
          cfg.get("subtitle", ""), cfg.get("info"),
          red_header=cfg.get("red_header", False))

    extra = EXTRA_ALL.get(cfg["file"], {})
    before = BEFORE_ALL.get(cfg["file"], {})
    n_pre = sum(len(v) for v in before.values())
    for title, blocks in cfg["sections"]:
        # 先输出挂在当前小节之前的补写章节（如结语前的内容）。
        # 用 get 而不是 pop：pop 会改写模块级字典，同一进程内二次构建同一份
        # 文档时这些小节会静默消失（调参脚本反复构建时就踩过）。
        for pre_title, pre_blocks in before.get(title, []):
            h1(doc, pre_title)
            render_blocks(doc, pre_blocks)
        h1(doc, title)
        merged = list(blocks) + list(extra.get(_key(title), []))
        render_blocks(doc, merged)

    sections_done = len(cfg["sections"]) + n_pre
    all_new = (list(NEW_SECTIONS.get(cfg["file"], []))
               + list(NEW_SECTIONS4.get(cfg["file"], []))
               + list(NEW_SECTIONS5.get(cfg["file"], [])))
    for title, blocks in all_new:
        h1(doc, title)
        render_blocks(doc, blocks)
        sections_done += 1

    if cfg.get("sign"):
        # 不给签字栏强制分页：实测分页后，末章内容不足一页的文档会出现
        # 「倒数第二页只剩两三行、下面空 20cm」的更难看的版式。
        h1(doc, f"{cn_num(sections_done + 1)}、审核意见")
        signature_block(doc, cfg["sign"], box_h_cm=SIGN_H.get(cfg["file"]) or None)

    # 二级标题统一定稿：按章重排为「章号.序」，消除缺号/跳号
    log = docx_kit.renumber_subheads(doc)
    if log:
        print(f"    小节重排 {len(log)} 处：{log[0]} …")

    # 图表引用兜底：标题后直接接表、图后接表等结构，逐张回改补不上
    added = docx_kit.cite_all(doc)
    if added:
        print(f"    补图表引用 {len(added)} 处：{'、'.join(added[:6])}")

    out = OUTDIR / cfg["file"]
    out.parent.mkdir(parents=True, exist_ok=True)
    doc.save(out)
    return out


def main():
    for cfg in TRACKS:
        out = build_one(cfg)
        print(f"✓ {out.name}")
    print(f"共 {len(TRACKS)} 份")


if __name__ == "__main__":
    main()
